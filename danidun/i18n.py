def set_language(lang: str = "") -> str:
    lang = (lang or winapi.ui_language()).lower()
    _current["lang"] = "es" if lang.startswith("es") else "en"
    return _current["lang"]


def t(key: str, **kwargs) -> str:
    """Translate ``key``; keys of the form 'prefix:argument' pass the argument as {arg}."""
    arg = None
    if ":" in key and key.split(":", 1)[0] in EN:
        key, arg = key.split(":", 1)
        if arg in EN:  # nested key, e.g. forced.err_folder_protected:protect.windows
            arg = t(arg)
        elif ":" in arg and arg.split(":", 1)[0] in EN:
            arg = t(arg)
    table = ES if _current["lang"] == "es" else EN
    text = table.get(key) or EN.get(key) or key
    if arg is not None:
        kwargs.setdefault("arg", arg)
        kwargs.setdefault("reason", arg)
    try:
        return text.format(**kwargs) if kwargs else text
    except (KeyError, IndexError, ValueError):
        return text
